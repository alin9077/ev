import {chromium} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import fs from 'node:fs';
const browser = await chromium.launch();
const context = await browser.newContext({viewport:{width:1440,height:1000}});
const page = await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:3001/');
await page.locator('.fleet-detail').first().waitFor();
await page.screenshot({path:'qa/screenshots/fleet-home-desktop.png'});
await page.locator('#detail-phone_key').scrollIntoViewIfNeeded();
await page.screenshot({path:'qa/screenshots/fleet-details-desktop.png'});
await page.setViewportSize({width:390,height:844});
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:'qa/screenshots/fleet-home-phone.png'});
await page.locator('.fleet-hero-row .swipe-track').scrollIntoViewIfNeeded();
await page.screenshot({path:'qa/screenshots/fleet-cards-phone.png'});
await page.locator('#detail-v2l').scrollIntoViewIfNeeded();
await page.screenshot({path:'qa/screenshots/fleet-conditional-phone.png'});
const overflow=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,items:[...document.querySelectorAll('main *')].filter(e=>!e.closest('.swipe-track')).filter(e=>e.getBoundingClientRect().right>innerWidth+2).map(e=>({cls:e.className,text:e.textContent.slice(0,50)})).slice(0,10)}));
const results=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
const report={errors,overflow,violations:results.violations.map(v=>({id:v.id,targets:v.nodes.map(n=>n.target)}))};
fs.writeFileSync('qa/fleet-accessibility.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report));
await browser.close();
