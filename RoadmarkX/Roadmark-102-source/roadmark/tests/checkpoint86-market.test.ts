import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { marketBeforeCheckpoint88 as market } from "./helpers/checkpoint88-history";
import evidence from "../data/market-element22-epoch-evidence-2026-10-11.json";
import { marketBeforeCheckpoint86 as before } from "./helpers/checkpoint86-history";
import { canonicalReviewedJson } from "../src/lib/correction-guards";
const row = market.records.find(r => r.id === "custom-denning-element")!;
const old = before.records.find(r => r.id === row.id)!;
test("Element2.2 changes only nine reviewed fields, all other239 rows and counts remain exact", () => {
  const diff = Object.keys(row).filter(k => JSON.stringify((row as Record<string, unknown>)[k]) !== JSON.stringify((old as Record<string, unknown>)[k]));
  assert.deepEqual(diff.sort(), ["aliases","modelAliases","sourceUrls","checkedAt","evidenceNote","limitations","sourceArtifacts","evidenceHistory","configurationEvidence"].sort());
  assert.deepEqual(market.records.filter(r => r.id !== row.id), before.records.filter(r => r.id !== row.id));
  assert.deepEqual(market.counts, before.counts);
  assert.equal(market.records.length, 240);
  assert.equal(market.counts.namedTrimConfigurationEntries, 393);
  assert.equal(market.records.filter(r => !r.trims.length).length, 53);
  assert.equal(market.complete, false);
  assert.equal(market.validation.completeMarketAudit, false);
});
test("Element2.2 source bytes, old evidence and conflicts stay recoverable", () => {
  assert.deepEqual(evidence.previousRecord, old);
  assert.equal(evidence.previousRecordCanonicalHashMethod, "SHA-256 of jq -S -c JSON serialization with one trailing LF");
  assert.equal(createHash("sha256").update(canonicalReviewedJson(old) + "\n").digest("hex"), evidence.previousRecordCanonicalSHA256);
  const bytes = readFileSync(new URL("../data/market-element22-epoch-evidence-2026-10-11.json", import.meta.url));
  assert.equal(createHash("sha256").update(bytes).digest("hex"), "0a625e8c3f44ff1bf48727ecf11abcc246a934d4aed1dd9b07859144269900f7");
  assert.equal(market.sourceArtifacts.at(-1)!.sha256, createHash("sha256").update(bytes).digest("hex"));
  for (const k of ["sourceUrls","limitations","sourceArtifacts","evidenceHistory"] as const) assert.deepEqual(row[k]!.slice(0, old[k]!.length), old[k]);
  assert.ok(row.evidenceNote.includes(old.evidenceNote));
  assert.equal(evidence.normalizationHolds.longBusSeatedPassengers, null);
  assert.equal(evidence.normalizationHolds.longBusTotalCapacity, null);
  assert.match(row.limitations.join(" "), /39 seated.*43 seated/);
  assert.match(row.limitations.join(" "), /411.5 kW/);
});
test("Two published lengths do not become trims, accepted orders, stock or rankings", () => {
  assert.deepEqual(row.trims, []);
  assert.equal(row.orderStatus, "listed_unconfirmed");
  assert.equal(row.stockStatus, "unverified");
  assert.equal(row.modelYear, null);
  assert.equal(row.rankingEligible, false);
  assert.equal(row.completeVehicleCountEligible, null);
  assert.equal(row.catalogueCoverage, "market_audit_only");
  assert.ok("configurationEvidence" in row);
  const configuration = row.configurationEvidence;
  assert.ok(configuration && !Array.isArray(configuration) && "lengthOptions" in configuration);
  assert.deepEqual(configuration.lengthOptions, evidence.publishedLengthOptions);
  assert.equal(configuration.fullyClosedFactoryBuild, false);
  assert.equal(configuration.detailedConfigurationCountContribution, 0);
  assert.equal(evidence.exactDetailedConfigurationProposalApproved, false);
  for (const [k,v] of Object.entries(evidence.countEffect)) if (k !== "qualification") assert.equal(v,0,k);
  for (const name of ["approved-corrections","approved-feature-corrections","approved-availability-corrections"]) assert.deepEqual(JSON.parse(readFileSync(new URL(`../data/${name}.json`,import.meta.url),"utf8")),[]);
});
