import test from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { marketBeforeCheckpoint89 as market } from "./helpers/checkpoint89-history";
import evidence from "../data/market-skywell-ecrew-evidence-2026-10-11.json";
import { marketBeforeCheckpoint88 as before, marketHash88 } from "./helpers/checkpoint88-history";
const row=market.records.find(r=>r.id==="skywell-ec11-e-crew")!;
const cargo=market.records.find(r=>r.id==="skywell-ec11-e-cargo")!;
const old=before.records.find(r=>r.id===cargo.id)!;
test("E-Crew fills one bus audit gap without duplicate lead or canonical-family admission",()=>{
  assert.equal(market.records.length,241);
  assert.equal(market.counts.byVehicleClass.bus,28);
  assert.equal(market.counts.byOrderStatus.listed_unconfirmed,193);
  assert.equal(market.counts.exactTrimSetMissingRecords,54);
  assert.equal(market.counts.namedTrimConfigurationEntries,393);
  assert.equal(market.counts.newStockListedModelRecords,68);
  assert.deepEqual(market.unverifiedLeads,before.unverifiedLeads);
  assert.deepEqual(market.reconciledLeads,before.reconciledLeads);
  assert.deepEqual(market.peripheralRecords,before.peripheralRecords);
  assert.ok(!Object.hasOwn(row,"familyId"));
  assert.equal(evidence.countEffect.detailedCanonicalFamilies,0);
  assert.equal(evidence.countEffect.detailedConfigurations,0);
  assert.equal(evidence.countEffect.verifiedAvailableVehicles,0);
  assert.equal(market.complete,false);
});
test("E-Crew preserves unverified exact-build, order, stock, approval and model-year scope",()=>{
  assert.deepEqual(row.trims,[]);
  assert.equal(row.vehicleClass,"bus");
  assert.equal(row.modelYear,null);
  assert.equal(row.orderStatus,"listed_unconfirmed");
  assert.equal(row.stockStatus,"unverified");
  assert.equal(row.rankingEligible,false);
  assert.equal(row.completeVehicleCountEligible,null);
  assert.match(row.evidenceNote,/12 including the driver/);
  assert.match(row.evidenceNote,/EOFY-2024/);
  assert.match(row.limitations.join(" "),/not evidence of E-Crew child-restraint/);
  assert.equal(evidence.holds.acceptedOrder,null);
  assert.equal(evidence.holds.approvalIdentity,null);
  assert.equal(evidence.exactDetailedConfigurationProposalApproved,false);
});
test("E-Cargo handoff changes exactly four fields and preserves its complete before state",()=>{
  const diff=Object.keys(cargo).filter(k=>JSON.stringify((cargo as Record<string,unknown>)[k])!==JSON.stringify((old as Record<string,unknown>)[k]));
  assert.deepEqual(diff.sort(),["limitations","sourceArtifacts","evidenceHistory","relatedRecordIds"].sort());
  assert.deepEqual(evidence.previousECargoRecord,old);
  assert.equal(marketHash88(old),evidence.previousECargoCanonicalSHA256);
  assert.deepEqual(cargo.evidenceHistory!.slice(0,old.evidenceHistory!.length),old.evidenceHistory);
  const latest=cargo.evidenceHistory!.at(-1)!;
  assert.ok("previousRecord" in latest);
  assert.deepEqual(latest.previousRecord,old);
  assert.equal(cargo.checkedAt,old.checkedAt);
  assert.equal(cargo.orderStatus,old.orderStatus);
  assert.equal(cargo.stockStatus,old.stockStatus);
  assert.deepEqual(market.records.filter(r=>r.id!==row.id&&r.id!==cargo.id),before.records.filter(r=>r.id!==cargo.id));
});
test("E-Crew evidence bytes bind to the reviewed source packet without changing correction registers",()=>{
  const bytes=readFileSync(new URL("../data/market-skywell-ecrew-evidence-2026-10-11.json",import.meta.url));
  assert.equal(createHash("sha256").update(bytes).digest("hex"),"ac5b8d45e14efb0b38931744feb43482781e58ae7f020c4a8d36b3d9dda2acd0");
  assert.equal(market.sourceArtifacts.at(-1)!.sha256,createHash("sha256").update(bytes).digest("hex"));
  assert.equal(evidence.sourcePacket.sealSHA256,"c1d4a57aa5b65c906ed97b4f696e350438747c8ce68a0c1a6312160fd7875c8d");
  assert.equal(evidence.sourcePacket.independentReviewSHA256,"6e95d1cd4f6f513fa4d3e24e1bf7982d5a923e3ef4d2faf87489d5f47673de1c");
  assert.deepEqual(evidence.proposedECrewRecord,row);
  assert.deepEqual(evidence.amendedECargoRecord,cargo);
  for(const name of ["approved-corrections","approved-feature-corrections","approved-availability-corrections"]) assert.deepEqual(JSON.parse(readFileSync(new URL(`../data/${name}.json`,import.meta.url),"utf8")),[]);
});
