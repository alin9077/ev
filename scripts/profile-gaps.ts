/**
 * Writes docs/PROFILES_GAPS.md: which Tier 1 families have a drawing made
 * from their own model, a body-type outline scaled to their own length,
 * height and wheelbase, or only the class silhouette.
 */
import { writeFileSync } from "node:fs";
import { catalogue } from "../src/lib/data";
import { avatarProfile, hasOwnWheelbase } from "../src/lib/car-avatar-shapes";
import { isTierOne } from "../src/lib/on-sale";

const cars = catalogue().filter(isTierOne);
const families = new Map<string, typeof cars>();
for (const car of cars)
  families.set(car.family, [...(families.get(car.family) ?? []), car]);
const rows = [...families].map(([family, versions]) => {
  const kinds = versions.map((v) => avatarProfile(v).kind);
  const dims = (key: string) =>
    versions.some((v) => typeof v.facts[key]?.value === "number");
  return {
    family,
    brand: versions[0].brand,
    model: versions[0].model,
    versions: versions.length,
    model_: kinds.filter((k) => k === "model").length,
    body: kinds.filter((k) => k === "body-type").length,
    cls: kinds.filter((k) => k === "class").length,
    missing: ["length_mm", "height_mm"].filter((k) => !dims(k)),
    typicalWheelbase: versions.filter(
      (v) => avatarProfile(v).kind === "body-type" && !hasOwnWheelbase(v),
    ).length,
    vehicleClass: versions[0].vehicleClass ?? "passenger",
    seats: Math.max(...versions.map((v) => Number(v.facts.seats?.value) || 0)),
  };
});
const typical = rows.filter((r) => r.typicalWheelbase > 0);
const fully = rows.filter((r) => r.cls === 0);
const partial = rows.filter((r) => r.cls > 0 && r.cls < r.versions);
const none = rows.filter((r) => r.cls === r.versions);
const reason = (r: (typeof rows)[number]) =>
  r.vehicleClass === "ute"
    ? "ute (no ute outline yet)"
    : r.missing.length
      ? `no published ${r.missing.map((m) => m.replace("_mm", "")).join(" or ")}`
      : r.seats >= 6
        ? "six or more seats (no people-mover outline yet)"
        : "length or height missing on some versions";
const list = (xs: typeof rows) =>
  xs
    .sort(
      (a, b) =>
        a.brand.localeCompare(b.brand) || a.model.localeCompare(b.model),
    )
    .map(
      (r) =>
        `- ${r.brand} ${r.model} (${r.versions} version${r.versions === 1 ? "" : "s"}): ${reason(r)}`,
    )
    .join("\n");
const text = `# Side-profile gaps (generated)

Generated by \`node --import tsx scripts/profile-gaps.ts\`. Do not edit by hand.

A drawing is made three ways. **Model**: hand-drawn for that model, to its own length, height and wheelbase (10 models). **Body type**: one of four hand-drawn outlines (compact, sedan, crossover, SUV) stretched to the version's own length, height and wheelbase; the outline style is shared within a body type, the proportions are the car's own. **Class silhouette**: the generic EV mark, used when a version has no published length or height, is a ute, or seats six or more. Where a wheelbase is not published, the drawing uses a typical wheelbase share of length (59%); it is a picture, not a stated figure.

| | Families | 
|---|---|
| Tier 1 families | ${rows.length} |
| Every version drawn to scale (model or body type) | ${fully.length} |
| Some versions only the class silhouette | ${partial.length} |
| Class silhouette only (no to-scale profile) | ${none.length} |
| Of the drawn families, with a wheelbase not published for some version (typical wheelbase used) | ${typical.length} |

## Families with no to-scale profile (${none.length})

${list(none)}

## Families where some versions fall back (${partial.length})

${list(partial)}
`;
writeFileSync("docs/PROFILES_GAPS.md", text);
console.log({
  families: rows.length,
  fully: fully.length,
  partial: partial.length,
  none: none.length,
});
